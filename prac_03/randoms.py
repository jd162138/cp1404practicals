import random

print(random.randint(5, 20))
# line 1: The smallest number could have been seen is 5 and the largest is 20
print(random.randrange(3, 10, 2))
# line 2: This line only produced odd numbers between 3 and 10 meaning the smallest was 3 and largest was 9
print(random.uniform(2.5, 5.5))
# line 3: The smallest number it could have produced is 2.5 and the largest is 5
